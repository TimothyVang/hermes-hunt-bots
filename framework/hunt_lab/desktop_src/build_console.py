"""Build the single-file native plugin and inline ESM console from pinned public source.

Requires Bun and the extracted noVNC commit beside its verified source.tar.gz.
No npm installation, dotenv loading, runtime CDN, or provider call is used.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile

HERE = Path(__file__).resolve().parent
DESKTOP = HERE.parent / 'desktop'
COMMIT = 'a8dfd6a3ea3c74244f5ebdaa5a7f1023007a7820'
ARCHIVE_SHA256 = 'ebb8eabcd3670ce1a02e4025f03976826c289121cf631183647bd8325b003403'


def verify_source(root: Path) -> int:
    root = root.resolve(strict=True)
    archive = root.parent / 'source.tar.gz'
    with archive.open('rb') as source:
        if hashlib.file_digest(source, 'sha256').hexdigest() != ARCHIVE_SHA256:
            raise ValueError('noVNC source archive does not match the pinned SHA256')
    prefix = 'noVNC-' + COMMIT + '/'
    count = 0
    with tarfile.open(archive, 'r:gz') as source:
        for member in source.getmembers():
            if not member.isfile() or not member.name.startswith(prefix):
                continue
            relative = member.name[len(prefix):]
            if not relative.startswith(('core/', 'vendor/')) and relative != 'package.json':
                continue
            path = root / relative
            if path.is_symlink() or not path.resolve(strict=True).is_relative_to(root):
                raise ValueError('Linked or escaping source file')
            if path.read_bytes() != source.extractfile(member).read():
                raise ValueError('Extracted source differs from the pinned upstream archive')
            count += 1
    if not (root / 'core' / 'rfb.js').is_file() or count == 0:
        raise ValueError('Expected the official noVNC browser ESM source')
    return count


def build(root: Path, output: Path) -> None:
    count = verify_source(root)
    bun = shutil.which('bun')
    if not bun:
        raise ValueError('Install Bun to rebuild the console; the shipped plugin needs no compiler')
    frontend = (HERE / 'console-frontend.js').read_text(encoding='utf-8')
    # Real ESM bundling retains upstream top-level await. A hand-written CJS
    # loader cannot preserve noVNC browser feature detection semantics.
    entry = 'import RFB from ' + json.dumps((root.resolve() / 'core' / 'rfb.js').as_posix()) + ';\n' + frontend
    allowed = {'PATH', 'PATHEXT', 'SYSTEMROOT', 'WINDIR', 'TEMP', 'TMP', 'COMSPEC',
               'USERPROFILE', 'LOCALAPPDATA', 'APPDATA', 'HOMEDRIVE', 'HOMEPATH'}
    environment = {k: v for k, v in os.environ.items() if k.upper() in allowed}
    with tempfile.TemporaryDirectory(prefix='hunt-console-build-') as temporary:
        folder = Path(temporary)
        (folder / 'entry.js').write_text(entry, encoding='utf-8', newline='\n')
        result = subprocess.run(
            [bun, 'build', '--no-env-file', str(folder / 'entry.js'), '--format', 'esm',
             '--target', 'browser', '--outfile', str(folder / 'console.mjs')],
            cwd=folder, env=environment, capture_output=True, text=True, timeout=60,
        )
        if result.returncode:
            raise RuntimeError('Bun console build failed: ' + result.stderr[-1500:])
        bundle = (folder / 'console.mjs').read_text(encoding='utf-8')
    factory = (HERE / 'console-frame.js').read_text(encoding='utf-8')
    native_entry = (HERE / 'plugin.entry.js').read_text(encoding='utf-8')
    generated = (
        '// Generated by hunt_lab/desktop_src/build_console.py; do not edit.\n'
        '// noVNC 1.6.0 MPL-2.0; notices in licenses/; provenance in console-provenance.json.\n'
        'const CONSOLE_BUNDLE = ' + json.dumps(bundle, ensure_ascii=True) + ';\n'
        + factory + '\nfunction consoleFrameUrl(wsURL) {\n'
        '  return createConsoleFrameUrl(CONSOLE_BUNDLE, wsURL);\n}\n' + native_entry
    )
    output.write_text(generated, encoding='utf-8', newline='\n')
    print(json.dumps({'plugin': str(output), 'verified_upstream_files': count,
                      'source_commit': COMMIT, 'format': 'inline-esm'}))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--novnc-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=DESKTOP / 'plugin.js')
    args = parser.parse_args()
    build(args.novnc_dir, args.output)


if __name__ == '__main__':
    main()
